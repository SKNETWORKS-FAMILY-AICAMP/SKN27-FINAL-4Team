// (월, 일) → 별자리 키. 경계일은 통용되는 서양식 날짜 구간.
const SEASONS = [
  [1, 20, 'aquarius'], [2, 19, 'pisces'], [3, 21, 'aries'], [4, 20, 'taurus'],
  [5, 21, 'gemini'], [6, 22, 'cancer'], [7, 23, 'leo'], [8, 23, 'virgo'],
  [9, 23, 'libra'], [10, 23, 'scorpio'], [11, 23, 'sagittarius'], [12, 22, 'capricorn'],
]

export function getSeasonConstellation(date = new Date()) {
  const m = date.getMonth() + 1
  const d = date.getDate()
  // SEASONS[i] = [시작월, 시작일, 키] — 해당 날짜 이후면 그 별자리, 아니면 직전 것
  let key = 'capricorn'   // 1/1~1/19는 전년 12/22 시작인 염소자리
  for (const [sm, sd, k] of SEASONS) {
    if (m > sm || (m === sm && d >= sd)) key = k
  }
  return { key, ...CONSTELLATIONS[key] }
}
